import { FormEvent, useState } from 'react';
import { Sparkles } from 'lucide-react';
import { Equipment } from '../types';
import { AiPlan, requestAiPlan } from '../services/aiPlanner';

interface Props {
  equipment: Equipment[];
  onRequest: (equipmentId: string) => void;
}

export default function AIProjectPlanner({ equipment, onRequest }: Props) {
  const [description, setDescription] = useState('');
  const [plan, setPlan] = useState<AiPlan | null>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    if (description.trim().length < 10) {
      setError('Please describe your project in at least 10 characters.');
      return;
    }
    setLoading(true);
    setError('');
    setPlan(null);
    try {
      const result = await requestAiPlan(description.trim(), equipment);
      if (!result.recommendations.length) setError('No matching equipment found. Try describing your project differently.');
      setPlan(result);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Something went wrong.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <section aria-labelledby="ai-heading" className="bg-white rounded-2xl border border-slate-200 shadow-sm p-7">
      <h3 id="ai-heading" className="text-xl font-bold text-slate-900 flex items-center gap-2">
        <Sparkles className="text-sky-700" aria-hidden="true" /> AI Project Planner
      </h3>
      <p className="text-sm text-slate-600 mt-1">
        Describe your project and Google Gemini suggests equipment from the catalogue. AI suggestions are advisory;
        FairSlot and faculty still decide allocation.
      </p>

      <form onSubmit={submit} className="mt-4 space-y-3">
        <label htmlFor="ai-desc" className="text-sm font-medium text-slate-800 block">
          What are you building?
        </label>
        <textarea
          id="ai-desc"
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          maxLength={600}
          rows={3}
          placeholder="e.g. A small robot that maps a corridor using LiDAR and needs a custom aluminium chassis"
          className="w-full border border-slate-300 rounded-lg px-3 py-2 text-sm focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-500"
        />
        <button
          type="submit"
          disabled={loading}
          className="inline-flex items-center gap-2 bg-sky-700 text-white px-4 py-2 rounded-lg text-sm font-medium hover:bg-sky-800 disabled:opacity-60 focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-500 focus-visible:ring-offset-2"
        >
          <Sparkles size={16} aria-hidden="true" /> {loading ? 'Asking Gemini…' : 'Get AI suggestions'}
        </button>
      </form>

      <div aria-live="polite">
        {error && <p role="alert" className="mt-4 text-sm bg-red-50 text-red-800 rounded-lg p-3">{error}</p>}
        {plan && plan.recommendations.length > 0 && (
          <div className="mt-5 space-y-4">
            {plan.summary && <p className="text-sm text-slate-800">{plan.summary}</p>}
            <ul className="space-y-3">
              {plan.recommendations.map((r) => (
                <li key={r.equipmentId} className="border border-slate-200 rounded-xl p-4 flex flex-wrap items-center justify-between gap-3">
                  <div>
                    <p className="font-semibold text-slate-900">{r.equipmentName}</p>
                    <p className="text-sm text-slate-600">{r.reason}</p>
                  </div>
                  <button
                    type="button"
                    onClick={() => onRequest(r.equipmentId)}
                    aria-label={`Request a slot for ${r.equipmentName}`}
                    className="px-3 py-1.5 rounded-lg text-sm bg-sky-700 text-white hover:bg-sky-800 focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-500 focus-visible:ring-offset-2"
                  >
                    Request slot
                  </button>
                </li>
              ))}
            </ul>
            <p className="text-sm text-slate-700">Suggested first session: <strong>{plan.suggestedHours} h</strong></p>
            {plan.tips.length > 0 && (
              <ul className="text-sm text-slate-700 list-disc pl-5">
                {plan.tips.map((t) => <li key={t}>{t}</li>)}
              </ul>
            )}
            <p className="text-xs text-slate-500">Generated by Google Gemini. Check suggestions with your supervisor.</p>
          </div>
        )}
      </div>
    </section>
  );
}
